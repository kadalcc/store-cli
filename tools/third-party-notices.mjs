#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md from what is installed: every package npm installs beside
 * @kadal/store (the dependencies in package.json, and theirs, all the way down), with the version
 * in node_modules, its licence as its own package.json states it, and the copyright lines of its
 * licence file.
 *
 *   bun install && node tools/third-party-notices.mjs           # rewrite the file
 *   node tools/third-party-notices.mjs --check                  # exit 1 if it is out of date
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(p, "utf8"));

/** Node's lookup: node_modules/<name> in this folder, then in each folder above, up to the root. */
function locate(name, from) {
  for (let dir = from; dir.startsWith(root); dir = dirname(dir)) {
    const at = join(dir, "node_modules", name);
    if (existsSync(join(at, "package.json"))) return at;
    if (dir === root) break;
  }
  return null;
}

const licenceOf = (pkg) =>
  typeof pkg.license === "string"
    ? pkg.license
    : (pkg.license?.type ?? pkg.licenses?.map((l) => l.type ?? l).join(" OR ") ?? "UNKNOWN");

const sourceOf = (pkg) => {
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  if (!repo) return pkg.homepage ?? `https://www.npmjs.com/package/${pkg.name}`;
  return repo
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^github:/, "https://github.com/")
    .replace(/^(?!https?:)([\w.-]+\/[\w.-]+)$/, "https://github.com/$1")
    .replace(/\.git$/, "");
};

/** The "Copyright …" lines of a package's licence file, or none if it has no file. */
function copyrights(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  if (!file) return [];
  const lines = readFileSync(join(dir, file), "utf8").split(/\r?\n/);
  return [
    ...new Set(lines.map((l) => l.trim()).filter((l) => /copyright\s+(\(c\)|©|\d)/i.test(l))),
  ];
}

const found = new Map();
const own = read(join(root, "package.json"));
const queue = Object.keys(own.dependencies ?? {}).map((name) => ({
  name,
  from: root,
  via: own.name,
}));
while (queue.length) {
  const { name, from, via } = queue.shift();
  const dir = locate(name, from);
  if (!dir) {
    // An optional dependency for another platform is simply not here.
    continue;
  }
  const pkg = read(join(dir, "package.json"));
  const key = `${pkg.name}@${pkg.version}`;
  if (found.has(key)) continue;
  found.set(key, { pkg, dir, via });
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies }))
    queue.push({ name: dep, from: dir, via: pkg.name });
}

const rows = [...found.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name));
const byLicence = new Map();
for (const r of rows) byLicence.set(licenceOf(r.pkg), (byLicence.get(licenceOf(r.pkg)) ?? 0) + 1);
const summary = [...byLicence]
  .sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `${n} ${l}`)
  .join(", ");

const md = `# Third-party notices

\`@kadal/store\` is AGPL-3.0-or-later (see [\`LICENSE\`](./LICENSE)). Its \`dist/\` is this
repository's own code: nothing from another package is copied or bundled into it. When you
install it, npm installs the packages below beside it, each under its own licence, which ships
in that package's folder in \`node_modules\`.

Generated by \`node tools/third-party-notices.mjs\` from the installed packages. The versions are
the ones this repository's lockfile resolves; npm may pick newer ones within the same ranges.

${rows.length} packages: ${summary}.

| Package | Version | Licence | Copyright | Source |
| --- | --- | --- | --- | --- |
${rows
  .map(({ pkg, dir }) => {
    const c =
      copyrights(dir)
        .map((l) => l.replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("|", "\\|"))
        .join("<br>") || "—";
    return `| \`${pkg.name}\` | ${pkg.version} | ${licenceOf(pkg)} | ${c} | ${sourceOf(pkg)} |`;
  })
  .join("\n")}

The pictures under \`.github/assets/\` are Kadal's: screenshots of store.kadal.cc and previews of
products sold there. They are not part of the npm package.
`;

const out = join(root, "THIRD_PARTY_NOTICES.md");
if (process.argv.includes("--check")) {
  const now = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (now !== md) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node tools/third-party-notices.mjs");
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${rows.length} packages).`);
} else {
  writeFileSync(out, md);
  console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages (${summary}).`);
}
